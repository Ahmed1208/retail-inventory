-- Keep identity sequence past manually inserted ids (app calls after create with explicit id).
CREATE OR REPLACE FUNCTION public.refresh_warehouse_id_sequence()
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  PERFORM setval(
    pg_get_serial_sequence('public.warehouses', 'id'),
    GREATEST((SELECT COALESCE(MAX(id), 1) FROM public.warehouses), 1)
  );
END;
$$;

GRANT EXECUTE ON FUNCTION public.refresh_warehouse_id_sequence() TO anon;
GRANT EXECUTE ON FUNCTION public.refresh_warehouse_id_sequence() TO authenticated;
GRANT EXECUTE ON FUNCTION public.refresh_warehouse_id_sequence() TO service_role;
